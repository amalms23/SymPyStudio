"""Bundle kernel/*.py and kernel/worker.js into kernel_bundle.js.

The browser loads the bundle with a plain <script> tag, so the app keeps working when
index.html is opened straight from disk (file://), where fetch() and file-backed Web
Workers are blocked.  The .py files stay the source of truth: edit them, then run

    python tools/build_kernel.py           # regenerate kernel_bundle.js
    python tools/build_kernel.py --check   # CI: fail if the bundle is stale
"""

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
KERNEL = os.path.join(ROOT, 'kernel')
OUT = os.path.join(ROOT, 'kernel_bundle.js')


def read(name):
    with open(os.path.join(KERNEL, name), encoding='utf-8') as fh:
        return fh.read().replace('\r\n', '\n')


def build():
    python = {
        'latex_parser': read('latex_parser.py'),
        'bootstrap': read('bootstrap.py'),
        'runner': read('runner.py'),
    }
    body = {'worker': read('worker.js'), 'python': python}
    return (
        '// GENERATED by tools/build_kernel.py from kernel/ - do not edit by hand.\n'
        'window.SYMPYSTUDIO_KERNEL = ' + json.dumps(body, ensure_ascii=False, indent=1) + ';\n'
    )


def main():
    text = build()
    if '--check' in sys.argv:
        try:
            with open(OUT, encoding='utf-8') as fh:
                current = fh.read().replace('\r\n', '\n')
        except FileNotFoundError:
            current = ''
        if current != text:
            print('kernel_bundle.js is out of date: run python tools/build_kernel.py')
            return 1
        print('kernel_bundle.js is up to date')
        return 0
    with open(OUT, 'w', encoding='utf-8', newline='\n') as fh:
        fh.write(text)
    print(f'wrote {os.path.relpath(OUT, ROOT)} ({len(text) // 1024} KB)')
    return 0


if __name__ == '__main__':
    sys.exit(main())
